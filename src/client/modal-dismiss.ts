/**
 * **弹窗的"非显式关闭"闸门**（用户口径："执行中不可点击空白取消，只能明确点取消或关闭"）。
 *
 * 为什么单独一个模块：这条规则同时被"点遮罩""按 Esc"两条路径用到，
 * 写在渲染代码里就会变成两处 if —— 而两处判断迟早会漂（一处记得看 `busy`、一处忘了）。
 * 抽出来还顺手可单测：**执行中不许被非显式动作关掉**，这条是硬要求，不该靠人眼审。
 *
 * 反面教材（本项目的真实事故类型）：AI 建树正在跑的时候，用户点了一下空白，
 * 弹窗消失、以为已经取消 —— 而模型调用还在继续烧 token，用户却看不到任何进度与结果。
 */
export function dismissibleByBackdrop(busy: boolean): boolean {
  return busy !== true;
}
